def load_external_dict(filepath):
    """
    從外部檔案載入額外的碼表
    支援格式：每行 "碼 字" 或 "碼\t字"
    例如：
        ab 明
        ab 朝
        cd 材
    """
    import os
    extra = {}
    if not os.path.exists(filepath):
        return extra
    try:
        with open(filepath, 'r', encoding='utf-8') as f:
            for line in f:
                line = line.strip()
                if not line or line.startswith('#'):
                    continue
                parts = line.split(None, 1)
                if len(parts) == 2:
                    code, char = parts
                    code = code.lower()
                    if code not in extra:
                        extra[code] = []
                    if char not in extra[code]:
                        extra[code].append(char)
    except Exception:
        pass
    return extra


def merge_dicts(base, extra):
    """合併兩個碼表，extra 中的字加到 base 對應碼的後面"""
    merged = dict(base)
    for code, chars in extra.items():
        if code in merged:
            for ch in chars:
                if ch not in merged[code]:
                    merged[code].append(ch)
        else:
            merged[code] = list(chars)
    return merged
